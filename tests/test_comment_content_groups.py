@pytest.mark.parametrize("text", [
    '//#define WARNING "Warning: /* choose the count before starting. */"',
    '//#define WARNING R"tag(Warning: /* choose the count */ and // continue)tag"',
    '//#define WARNING R"(literal /* text */)" /* Explain this warning to the user. */',
    "//#define F(x, y",
    "//#define 12 invalid macro name",
])
def test_incomplete_or_parser_unsupported_macro_syntax_stays_explicitly_unknown_not_prose(text):
    # Valid quoted/raw-block macro values expose a tree-sitter preproc_arg
    # limitation. They must not be asserted natural prose, nor promoted to
    # supported code by reconstructing a different program for the parser.
    classified = classify_comment_content(text, "cpp")
    assert classified.group == "unknown", classified
    assert "macro" in classified.reason.lower()
    assert "unsupported" in classified.reason.lower() or "incomplete" in classified.reason.lower()
