def test_classifier_contract_is_deterministic_and_has_no_label_inputs():
    assert set(GROUPS) == {
        "code_like", "separator", "metadata", "prose", "mixed_unknown", "unknown"
    }
    assert set(inspect.signature(classify_comment_content).parameters) == {
        "text", "language", "syntax_form"
    }
    fixtures = [
        ("// int count = 3;", "java", "line"),
        ("# Return the smallest value in the input list.", "python", "line"),
        ("// count", "cpp", "line"),
    ]
    for args in fixtures:
        first = classify_comment_content(*args)
        assert first.group in GROUPS
        assert isinstance(first.reason, str) and first.reason.strip()
        assert isinstance(first.body, str)
        for _ in range(10):
            repeated = classify_comment_content(*args)
            assert (repeated.group, repeated.reason, repeated.body) == (
                first.group, first.reason, first.body
            )


def test_aggregation_partitions_original_loss_and_bytes_not_normalized_bodies():
    source = "π = 1;\n// Compute the sum for α.\n// -------\nint x = 0;\n// count"
    raw_comments = ["// Compute the sum for α.", "// -------", "// count"]
    spans = [SimpleNamespace(start=source.index(raw), end=source.index(raw) + len(raw))
             for raw in raw_comments]
    # Marker bytes deliberately have higher loss. Duplicate Unicode offsets
    # accumulate information without duplicating the byte denominator.
    losses = []
    density = []
    for index, char in enumerate(source):
        bits_per_byte = 9.0 if char == "/" else (3.0 if char == "-" else 1.0)
        density.append(bits_per_byte * (2.0 if char == "α" else 1.0))
        for _ in range(2 if char == "α" else 1):
            losses.append(TokenLoss(len(losses), index, index + 1,
                                    bits_per_byte * len(char.encode("utf-8")) * math.log(2.0)))
    values, occurrences = aggregate_content_groups(source, losses, spans, "cpp")
    assert [row["content_group"] for row in occurrences] == ["prose", "separator", "unknown"]
    total_bits = total_bytes = 0.0
    for group, span, raw, occurrence in zip(("prose", "separator", "unknown"), spans, raw_comments, occurrences):
        expected_bytes = len(raw.encode("utf-8"))
        expected_bits = sum(density[index] * len(source[index].encode("utf-8"))
                            for index in range(span.start, span.end))
        assert values[group + "__covered_bytes"] == expected_bytes
        assert values[group + "__bits"] == pytest.approx(expected_bits, abs=1e-10)
        assert values[PREFIX + group + "__bpb_mean"] == pytest.approx(expected_bits / expected_bytes)
        assert occurrence["raw_comment"] == raw
        assert occurrence["start"] == span.start and occurrence["end"] == span.end
        assert occurrence["covered_bytes"] == expected_bytes
        assert occurrence["bits"] == pytest.approx(expected_bits)
        total_bits += expected_bits
        total_bytes += expected_bytes
    assert values["all_comment_covered_bytes"] == total_bytes
    assert values["all_comment_bpb"] == pytest.approx(total_bits / total_bytes)
    assert sum(values[group + "__bits"] for group in GROUPS) == pytest.approx(total_bits)
    assert sum(values[group + "__covered_bytes"] for group in GROUPS) == total_bytes
    assert values[PREFIX + "prose__bpb_mean"] > 1.0
    assert np.isnan(values[PREFIX + "code_like__bpb_mean"])


def test_absent_groups_are_undefined_bpb_not_zero_difficulty():
    values, occurrences = aggregate_content_groups("x", [TokenLoss(0, 0, 1, math.log(2.0))], [], "cpp")
    assert occurrences == []
    assert values["all_comment_bpb"] is None
    assert values["all_comment_covered_bytes"] == 0
    for group in GROUPS:
        assert np.isnan(values[PREFIX + group + "__bpb_mean"])
        assert values[group + "__covered_bytes"] == 0
        assert values[group + "__bits"] == 0
        assert values[group + "__occurrence_count"] == 0


def test_cross_group_overlapping_original_spans_are_not_silently_called_partition():
    source = "/* Compute the sum for values. // ----- */"
    nested_start, nested_end = source.index("//"), source.index(" */")
    spans = [SimpleNamespace(start=0, end=len(source)),
             SimpleNamespace(start=nested_start, end=nested_end)]
    losses = [TokenLoss(index, index, index + 1, math.log(2.0)) for index in range(len(source))]
    with pytest.raises(ValueError, match="overlap"):
        aggregate_content_groups(source, losses, spans, "cpp")


